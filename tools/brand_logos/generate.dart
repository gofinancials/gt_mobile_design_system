// Writes lib/common/assets/gt_brand_logos.dart from gt_images'
// brand_logos/manifest.json:
//
//   dart tools/brand_logos/generate.dart ../gt_images/brand_logos/manifest.json
//
// then run `dart format` on the output.
import 'dart:convert';
import 'dart:io';

import 'package:gt_mobile_ui/common/assets/gt_brand_key.dart';

/// Names the gateway uses that share no key with the Figma name.
const _aliases = <String, List<String>>{
  'banks/9_payment_service_bank.webp': ['9PSB'],
  'banks/airtel_smartcash_psb.webp': ['SmartCash PSB'],
  'banks/alat_by_wema.webp': ['ALAT'],
  'banks/first_bank_of_nigeria.webp': ['FirstBank', 'FBN'],
  'banks/first_city_monument_bank.webp': ['FCMB'],
  'banks/gtbank_plc.webp': ['Guaranty Trust Bank', 'GTB', 'GTCO'],
  'banks/mtn_momo_psb.webp': ['MoMo PSB'],
  'banks/stanbic_ibtc_bank.webp': ['Stanbic'],
  'banks/united_bank_for_africa.webp': ['UBA'],
  'billers/glo.webp': ['Globacom'],
  'billers/phedc_ph.webp': ['Port Harcourt'],
  'billers/startime.webp': ['StarTimes'],
  'billers/t2_mobile.webp': ['9mobile', 'Etisalat'],
};

void main(List<String> args) {
  final manifest = jsonDecode(File(args.single).readAsStringSync()) as Map;
  final logos = (manifest['logos'] as List).cast<Map<String, dynamic>>();
  final banks = <String, String>{};
  final billers = <String, String>{};

  void add(Map<String, String> map, String name, String path) {
    final key = gtBrandKey(name);
    if (key.isEmpty) return;
    final taken = map[key];
    if (taken != null && taken != path) {
      stderr.writeln('$name: `$key` already names $taken, not $path');
      return;
    }
    map[key] = path;
  }

  Map<String, String> mapOf(String path) {
    return path.startsWith('billers/') ? billers : banks;
  }

  final paths = {for (final logo in logos) logo['path']};
  for (final path in _aliases.keys.where((path) => !paths.contains(path))) {
    stderr.writeln('alias for $path, which the manifest does not list');
  }

  // Aliases first: "FCMB" is the commercial bank, not "FCMB MFB", whose key
  // is also `fcmb`. Then whole names, so no name part takes a brand's key.
  for (final MapEntry(key: path, value: names) in _aliases.entries) {
    for (final name in names) {
      add(mapOf(path), name, path);
    }
  }
  for (final logo in logos) {
    add(mapOf(logo['path']), logo['name'], logo['path']);
  }
  for (final logo in logos) {
    final String path = logo['path'];
    final String name = logo['name'];
    final parts = gtBrandNameParts(name).skip(1).toList();
    // Electricity companies are named "IKEDC - Ikeja"; the gateway uses either.
    if (path.startsWith('billers/')) parts.addAll(name.split(' - '));
    for (final part in parts) {
      add(mapOf(path), part, path);
    }
  }

  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tools/brand_logos/generate.dart from gt_images\'',
    )
    ..writeln('// brand_logos/manifest.json. Do not edit by hand.')
    ..writeln()
    ..writeln(
      '/// Bank logo paths under gt_images/brand_logos, by [gtBrandKey].',
    )
    ..writeln('const gtBankLogoPaths = <String, String>{');
  for (final key in banks.keys.toList()..sort()) {
    out.writeln("  '$key': '${banks[key]}',");
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln(
      '/// Biller logo paths under gt_images/brand_logos, by [gtBrandKey].',
    )
    ..writeln('const gtBillerLogoPaths = <String, String>{');
  for (final key in billers.keys.toList()..sort()) {
    out.writeln("  '$key': '${billers[key]}',");
  }
  out.writeln('};');
  File('lib/common/assets/gt_brand_logos.dart').writeAsStringSync('$out');
  stdout.writeln('${banks.length} bank keys, ${billers.length} biller keys');
}
